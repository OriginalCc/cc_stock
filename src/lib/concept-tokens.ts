const TOKEN_STOPWORDS = ["概念", "板块", "相关", "指数", "龙头", "综合"] as const;

/** 预排序词典（长词优先，同长原地序），避免每次调用重复排序 */
const LEXICON_SORTED = [...new Set(CONCEPT_ROOT_LEXICON)]
  .filter(w => w.length >= 2 && !TOKEN_STOPWORDS.some(sw => w.includes(sw)))
  .sort((a, b) => b.length - a.length);

export function extractConceptTokens(name: string, vocab: Iterable<string>): string[] {
  const trimmed = name.trim();
  // 剥离通用后缀后再分词（全名本身仍作为第一优先 token 由调用方保留）
  const clean = trimmed.replace(/(?:概念|板块)+$/, "");
  if (clean.length < 2) return [];
  const others = [...new Set(vocab)].filter(v => v && v !== trimmed);
  const tokens: string[] = [];
  let i = 0;
  while (i < clean.length) {
    let matched: string | null = null;
    // 1) 词典最长匹配（人工整理根词，不受其他概念名数量限制）
    for (const w of LEXICON_SORTED) {
      if (w.length <= clean.length - i && clean.startsWith(w, i)) {
        matched = w;
        break;
      }
    }
    // 2) 数据挖掘兜底：其他概念名中的共享最长子串（≥1 个其他概念名共享即成立；
    //    经全量词根审查无垃圾碎片——词典已覆盖常见根，挖掘只处理词典外的新题材）
    if (!matched && others.length > 0) {
      for (let len = clean.length - i; len >= 2; len--) {
        const sub = clean.slice(i, i + len);
        if (TOKEN_STOPWORDS.some(sw => sub.includes(sw))) continue;
        if (others.some(v => v.includes(sub))) {
          matched = sub;
          break;
        }
      }
    }
    if (matched) {
      tokens.push(matched);
      i += matched.length;
    } else {
      i += 1; // 单字无区分度，跳过
    }
  }
  return tokens;
}
